const parseGrid = (rows: string[]): TileType[][] => {
  const map: Record<string, TileType> = {
    '.': 'empty',
    '#': 'wall',
    '~': 'puddle',
    'S': 'sprout',
    'B': 'battery',
    'G': 'goal',
  };
  return rows.map((row) => row.split('').map((ch) => map[ch] ?? 'empty'));
};

